# PEP 8 membahas beberapa bagian:
# Indentasi: Gunakan 4 spasi untuk setiap tingkat indentasi.
# Penamaan variabel: Gunakan huruf kecil dan garis bawah jika terdiri dari beberapa kata, misalnya favorite_foods.
# Spasi: Berikan spasi di sekitar operator, misalnya angka = 10 + 5.
# Panjang baris: Usahakan panjang setiap baris kode maksimal 79 karakter.
# Baris kosong: Gunakan secukupnya untuk memisahkan bagian kode.

